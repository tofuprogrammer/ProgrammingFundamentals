#include <iostream> // Allows usage of input and output functions such as std::cout.

int main() // Starting point for the program.
{
    std::cout << "*\n"; // Outputs the first line of the triangle to the console and starts a new line.
    std::cout << "**\n"; // Outputs the second line of the triangle to the console and starts a new line.
    std::cout << "* *\n"; // Outputs the third line of the triangle to the console and starts a new line.
    std::cout << "****\n"; // Outputs the final line of the triangle to the console and starts a new line.
}