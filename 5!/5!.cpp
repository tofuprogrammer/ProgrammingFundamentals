#include <iostream> // Allows usage of input and output functions such as std::cout.

int main() // Starting point for the program.
{
    const int factorial = 5 * 4 * 3 * 2 * 1; // Defines "factorial" as a constant variable of type int (integer) and initialises it to the value 120 (5 * 4 * 3 * 2 * 1).
    std::cout << factorial; // Outputs the value of the variable "factorial" (120) to the console without starting a new line.
}